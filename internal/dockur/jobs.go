// Guest jobs run through a file protocol in the shared folder, served by a
// small PowerShell agent that the OEM install script registers (see
// agent.ps1). Per job, <shared>/.kryton/jobs/<id>/ holds:
//
//	script.cmd|script.ps1  written by Kryton
//	job.json               written by Kryton last: the agent's pick-up signal
//	status.json            written by the agent: running | done | timed_out | canceled
//	stdout.log             combined stdout/stderr, written by the agent
//	cancel                 created by Kryton to request cancellation
//	artifacts/             the job's $env:KRYTON_ARTIFACTS directory
//
// Everything the guest writes is treated as untrusted input.

//go:embed agent.ps1
var agentScript string

const (
	agentHeartbeat = "agent-ready"
	maxStatusBytes = 64 * 1024
	// runOverrun is how long past its timeout a running job may go
	// unreported before Kryton gives up on the agent.
	runOverrun = time.Minute
)

var jobIDRE = regexp.MustCompile(`^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$`)

func toCRLF(s string) string {
	s = strings.ReplaceAll(s, "\r\n", "\n")
	return strings.ReplaceAll(s, "\n", "\r\n")
}

// buildInstallBat renders /oem/install.bat: the optional agent bootstrap
// followed by the operator's OEM script.
func buildInstallBat(d *model.DockurOptions) string {
	var b strings.Builder
	b.WriteString("@echo off\n")
	b.WriteString("rem Generated by Kryton from the machine's dockur options.\n")
	if d.JobAgent {
		b.WriteString(`mkdir "%ProgramData%\Kryton" >nul 2>&1` + "\n")
		b.WriteString(`copy /Y "%~dp0kryton-agent.ps1" "%ProgramData%\Kryton\agent.ps1" >nul` + "\n")
		b.WriteString(`> "%ProgramData%\Microsoft\Windows\Start Menu\Programs\StartUp\kryton-agent.cmd" echo @start "" /B powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "%ProgramData%\Kryton\agent.ps1"` + "\n")
		b.WriteString(`start "" /B powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "%ProgramData%\Kryton\agent.ps1"` + "\n")
	}
	if d.OemScript != "" {
		b.WriteString("rem ---- operator script ----\n")
		b.WriteString(d.OemScript)
		b.WriteString("\n")
	}
	return toCRLF(b.String())
}

// jobRecord is job.json: the public job plus agent-facing fields.
type jobRecord struct {
	model.GuestJob
	ScriptFile string            `json:"scriptFile"`
	Env        map[string]string `json:"env,omitempty"`
}

type agentStatus struct {
	State      string `json:"state"`
	ExitCode   *int   `json:"exitCode"`
	StartedAt  string `json:"startedAt"`
	FinishedAt string `json:"finishedAt"`
}

type pendingEvent struct {
	typ, subject string
	data         map[string]any
}

func (p *Provider) jobsRoot(mi machineInfo) (string, error) {
	root, err := p.sharedRoot(mi)
	if err != nil {
		return "", err
	}
	if mi.m.Spec.Dockur == nil || !mi.m.Spec.Dockur.JobAgent {
		return "", errf(provider.ErrPrecondition, "machine was created without the guest job agent (dockur.jobAgent); jobs need it installed at first boot")
	}
	return root, nil
}

func jobRel(jobID string) string { return path.Join(reservedDir, "jobs", jobID) }

func validJobID(jobID string) error {
	if !jobIDRE.MatchString(jobID) {
		return provider.ErrNotFound
	}
	return nil
}

// SubmitJob queues a script for the guest agent.
func (p *Provider) SubmitJob(ctx context.Context, project, machineID string, spec model.GuestJobSpec) (*model.GuestJob, error) {
	mi, err := p.lookup(project, machineID)
	if err != nil {
		return nil, err
	}
	root, err := p.jobsRoot(mi)
	if err != nil {
		return nil, err
	}
	if err := spec.Normalize(); err != nil {
		return nil, errf(provider.ErrInvalid, "%v", err)
	}
	jobID := id.New()
	rel := jobRel(jobID)
	full, err := resolveIn(root, rel, true)
	if err != nil {
		return nil, err
	}
	if err := os.MkdirAll(filepath.Join(full, "artifacts"), 0o755); err != nil { // #nosec G301 -- written by the guest
		return nil, err
	}
	scriptFile := "script.cmd"
	if spec.Shell == "powershell" {
		scriptFile = "script.ps1"
	}
	script := toCRLF(spec.Script)
	if spec.Shell == "cmd" && !strings.HasPrefix(strings.ToLower(strings.TrimSpace(script)), "@echo off") {
		script = "@echo off\r\n" + script
	}
	if err := os.WriteFile(filepath.Join(full, scriptFile), []byte(script), 0o644); err != nil { // #nosec G306 -- read by the guest
		return nil, err
	}
	rec := jobRecord{
		GuestJob: model.GuestJob{
			ID: jobID, Project: project, MachineID: machineID, Name: spec.Name, Shell: spec.Shell,
			State: model.GuestJobQueued, TimeoutSeconds: spec.TimeoutSeconds, SubmittedAt: time.Now().UTC(),
		},
		ScriptFile: scriptFile, Env: spec.Env,
	}
	p.jmu.Lock()
	err = writeJSONAtomic(filepath.Join(full, "job.json"), rec)
	sink := p.sink
	p.jmu.Unlock()
	if err != nil {
		return nil, err
	}
	if sink != nil {
		sink(ctx, "io.kryton.machine.job.submitted", "machines/"+machineID+"/jobs/"+jobID, map[string]any{
			"project": project, "machineId": machineID, "jobId": jobID, "name": spec.Name, "shell": spec.Shell,
		})
	}
	job := rec.GuestJob
	return &job, nil
}

func writeJSONAtomic(path string, v any) error {
	b, err := json.Marshal(v)
	if err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, b, 0o644); err != nil { // #nosec G306 -- read by the guest
		return err
	}
	return os.Rename(tmp, path)
}

func readCapped(path string, max int64) ([]byte, error) {
	f, err := os.Open(path) // #nosec G304 -- inside the symlink-checked job directory
	if err != nil {
		return nil, err
	}
	defer func() { _ = f.Close() }()
	b, err := io.ReadAll(io.LimitReader(f, max))
	return bytes.TrimPrefix(b, []byte("\xef\xbb\xbf")), err
}

// loadJob reads and refreshes one job; callers hold p.jmu. Terminal
// transitions are returned as events to publish after unlocking.
func (p *Provider) loadJobLocked(mi machineInfo, root, jobID string) (*jobRecord, []pendingEvent, error) {
	full, err := resolveIn(root, jobRel(jobID), true)
	if err != nil {
		return nil, nil, err
	}
	b, err := readCapped(filepath.Join(full, "job.json"), 1<<20)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil, provider.ErrNotFound
		}
		return nil, nil, err
	}
	var rec jobRecord
	if err := json.Unmarshal(b, &rec); err != nil {
		return nil, nil, errf(provider.ErrInvalid, "corrupt job record")
	}
	rec.ID, rec.Project, rec.MachineID = jobID, mi.m.Project, mi.m.ID
	var events []pendingEvent
	if p.refreshJob(&rec, full) {
		if model.GuestJobTerminal(rec.State) && !rec.Notified {
			rec.Notified = true
			data := map[string]any{
				"project": rec.Project, "machineId": rec.MachineID, "jobId": rec.ID, "name": rec.Name,
				"state": rec.State, "message": rec.Message,
			}
			if rec.ExitCode != nil {
				data["exitCode"] = *rec.ExitCode
			}
			if rec.StartedAt != nil && rec.FinishedAt != nil {
				data["durationSeconds"] = rec.FinishedAt.Sub(*rec.StartedAt).Seconds()
			}
			events = append(events, pendingEvent{"io.kryton.machine.job.completed", "machines/" + rec.MachineID + "/jobs/" + rec.ID, data})
		}
		if err := writeJSONAtomic(filepath.Join(full, "job.json"), rec); err != nil {
			return &rec, events, err
		}
	}
	return &rec, events, nil
}

func parseTime(s string) *time.Time {
	t, err := time.Parse(time.RFC3339Nano, s)
	if err != nil {
		return nil
	}
	t = t.UTC()
	return &t
}

// refreshJob folds the agent's status.json (and host-side timeouts) into
// rec; it reports whether rec changed.
func (p *Provider) refreshJob(rec *jobRecord, full string) bool {
	if model.GuestJobTerminal(rec.State) {
		return false
	}
	before := *rec
	now := time.Now().UTC()
	finish := func(state, msg string) {
		rec.State, rec.Message = state, msg
		rec.FinishedAt = &now
	}
	if b, err := readCapped(filepath.Join(full, "status.json"), maxStatusBytes); err == nil {
		var st agentStatus
		if json.Unmarshal(b, &st) == nil {
			if t := parseTime(st.StartedAt); t != nil && rec.StartedAt == nil {
				rec.StartedAt = t
			}
			fin := parseTime(st.FinishedAt)
			if fin != nil {
				now = *fin
			}
			switch st.State {
			case "running":
				rec.State = model.GuestJobRunning
				if rec.StartedAt == nil {
					s := now
					rec.StartedAt = &s
				}
			case "done":
				rec.ExitCode = st.ExitCode
				if st.ExitCode != nil && *st.ExitCode == 0 {
					finish(model.GuestJobSucceeded, "")
				} else {
					finish(model.GuestJobFailed, "script exited with a non-zero code")
				}
			case "timed_out":
				finish(model.GuestJobTimedOut, "job exceeded its timeout and was killed")
			case "canceled":
				finish(model.GuestJobCanceled, "job was canceled")
			case "failed":
				finish(model.GuestJobFailed, "guest agent could not run the job")
			}
		}
	}
	if !model.GuestJobTerminal(rec.State) {
		now = time.Now().UTC()
		timeout := time.Duration(rec.TimeoutSeconds) * time.Second
		switch {
		case rec.StartedAt != nil && now.Sub(*rec.StartedAt) > timeout+runOverrun:
			_ = os.WriteFile(filepath.Join(full, "cancel"), nil, 0o644) // #nosec G306 -- guest-readable marker
			finish(model.GuestJobTimedOut, "timeout exceeded and the guest agent did not report completion")
		case rec.StartedAt == nil && now.Sub(rec.SubmittedAt) > p.queueTimeout:
			_ = os.WriteFile(filepath.Join(full, "cancel"), nil, 0o644) // #nosec G306 -- guest-readable marker
			finish(model.GuestJobFailed, "no guest agent picked up the job (is the guest running and logged in?)")
		}
	}
	return rec.State != before.State || rec.Message != before.Message || rec.StartedAt != before.StartedAt || rec.CancelRequest != before.CancelRequest
}

func (p *Provider) emit(ctx context.Context, events []pendingEvent) {
	p.jmu.Lock()
	sink := p.sink
	p.jmu.Unlock()
	if sink == nil {
		return
	}
	for _, e := range events {
		sink(ctx, e.typ, e.subject, e.data)
	}
}

// GetJob returns one job, refreshed from the guest's status file, with its
// artifact listing.
func (p *Provider) GetJob(ctx context.Context, project, machineID, jobID string) (*model.GuestJob, error) {
	mi, root, err := p.jobCtx(project, machineID, jobID)
	if err != nil {
		return nil, err
	}
	p.jmu.Lock()
	rec, events, err := p.loadJobLocked(mi, root, jobID)
	p.jmu.Unlock()
	p.emit(ctx, events)
	if err != nil && rec == nil {
		return nil, err
	}
	job := rec.GuestJob
	job.Artifacts, _ = listArtifacts(root, jobID, "")
	return &job, nil
}

func (p *Provider) jobCtx(project, machineID, jobID string) (machineInfo, string, error) {
	mi, err := p.lookup(project, machineID)
	if err != nil {
		return mi, "", err
	}
	root, err := p.jobsRoot(mi)
	if err != nil {
		return mi, "", err
	}
	return mi, root, validJobID(jobID)
}

// ListJobs lists the machine's jobs, newest first (at most 200).
func (p *Provider) ListJobs(ctx context.Context, project, machineID string) ([]model.GuestJob, error) {
	mi, err := p.lookup(project, machineID)
	if err != nil {
		return nil, err
	}
	root, err := p.jobsRoot(mi)
	if err != nil {
		return nil, err
	}
	entries, err := os.ReadDir(filepath.Join(root, reservedDir, "jobs"))
	if err != nil {
		if os.IsNotExist(err) {
			return []model.GuestJob{}, nil
		}
		return nil, err
	}
	out := []model.GuestJob{}
	var events []pendingEvent
	p.jmu.Lock()
	for _, e := range entries {
		if !e.IsDir() || !jobIDRE.MatchString(e.Name()) {
			continue
		}
		rec, ev, _ := p.loadJobLocked(mi, root, e.Name())
		if rec == nil {
			continue
		}
		events = append(events, ev...)
		out = append(out, rec.GuestJob)
	}
	p.jmu.Unlock()
	p.emit(ctx, events)
	sort.Slice(out, func(i, j int) bool { return out[i].SubmittedAt.After(out[j].SubmittedAt) })
	if len(out) > 200 {
		out = out[:200]
	}
	return out, nil
}

// CancelJob asks the agent to kill a running job; a job nobody has started
// yet is canceled immediately.
func (p *Provider) CancelJob(ctx context.Context, project, machineID, jobID string) (*model.GuestJob, error) {
	mi, root, err := p.jobCtx(project, machineID, jobID)
	if err != nil {
		return nil, err
	}
	full, err := resolveIn(root, jobRel(jobID), true)
	if err != nil {
		return nil, err
	}
	p.jmu.Lock()
	rec, events, err := p.loadJobLocked(mi, root, jobID)
	if err != nil && rec == nil {
		p.jmu.Unlock()
		return nil, err
	}
	if !model.GuestJobTerminal(rec.State) {
		_ = os.WriteFile(filepath.Join(full, "cancel"), nil, 0o644) // #nosec G306 -- guest-readable marker
		rec.CancelRequest = true
		if rec.State == model.GuestJobQueued {
			if _, serr := os.Stat(filepath.Join(full, "status.json")); os.IsNotExist(serr) {
				_ = writeJSONAtomic(filepath.Join(full, "status.json"), agentStatus{State: "canceled"})
				now := time.Now().UTC()
				rec.State, rec.Message, rec.FinishedAt = model.GuestJobCanceled, "job was canceled before it started", &now
			}
		} else {
			rec.Message = "cancel requested; waiting for the guest agent"
		}
		if model.GuestJobTerminal(rec.State) && !rec.Notified {
			rec.Notified = true
			events = append(events, pendingEvent{"io.kryton.machine.job.completed", "machines/" + machineID + "/jobs/" + jobID, map[string]any{
				"project": project, "machineId": machineID, "jobId": jobID, "name": rec.Name, "state": rec.State, "message": rec.Message,
			}})
		}
		_ = writeJSONAtomic(filepath.Join(full, "job.json"), rec)
	}
	p.jmu.Unlock()
	p.emit(ctx, events)
	job := rec.GuestJob
	return &job, nil
}

// JobLog reads a window of the job's combined output.
func (p *Provider) JobLog(_ context.Context, project, machineID, jobID string, offset, limit int64) ([]byte, int64, error) {
	_, root, err := p.jobCtx(project, machineID, jobID)
	if err != nil {
		return nil, 0, err
	}
	f, fi, err := openFile(root, path.Join(jobRel(jobID), "stdout.log"), true)
	if err != nil {
		if err == provider.ErrNotFound {
			return []byte{}, 0, nil // not started yet
		}
		return nil, 0, err
	}
	defer func() { _ = f.Close() }()
	if offset < 0 {
		offset = 0
	}
	if limit <= 0 || limit > 4<<20 {
		limit = 4 << 20
	}
	buf := make([]byte, limit)
	n, err := f.ReadAt(buf, offset)
	if err != nil && err != io.EOF {
		return nil, 0, err
	}
	return buf[:n], fi.Size, nil
}

func listArtifacts(root, jobID, sub string) ([]model.SharedFile, error) {
	base := path.Join(jobRel(jobID), "artifacts")
	var out []model.SharedFile
	var walk func(rel string, depth int) error
	walk = func(rel string, depth int) error {
		items, err := listDir(root, path.Join(base, rel), true)
		if err != nil {
			return err
		}
		for _, it := range items {
			r := path.Join(rel, it.Name)
			if it.IsDir {
				if depth < 8 {
					if err := walk(r, depth+1); err != nil {
						return err
					}
				}
				continue
			}
			it.Path = r
			out = append(out, it)
			if len(out) >= 1000 {
				return nil
			}
		}
		return nil
	}
	if err := walk(sub, 0); err != nil && err != provider.ErrNotFound {
		return nil, err
	}
	return out, nil
}

// ListArtifacts lists files the job left in its artifacts directory
// (paths are relative to it).
func (p *Provider) ListArtifacts(_ context.Context, project, machineID, jobID string) ([]model.SharedFile, error) {
	_, root, err := p.jobCtx(project, machineID, jobID)
	if err != nil {
		return nil, err
	}
	out, err := listArtifacts(root, jobID, "")
	if out == nil {
		out = []model.SharedFile{}
	}
	return out, err
}

// OpenArtifact opens one artifact file (rel is relative to artifacts/).
func (p *Provider) OpenArtifact(_ context.Context, project, machineID, jobID, rel string) (*os.File, model.SharedFile, error) {
	_, root, err := p.jobCtx(project, machineID, jobID)
	if err != nil {
		return nil, model.SharedFile{}, err
	}
	rel = strings.Trim(rel, "/")
	if rel == "" {
		return nil, model.SharedFile{}, errf(provider.ErrInvalid, "artifact path is required")
	}
	if err := model.ValidateRelPath(rel, true); err != nil {
		return nil, model.SharedFile{}, errf(provider.ErrInvalid, "%v", err)
	}
	f, sf, err := openFile(root, path.Join(jobRel(jobID), "artifacts", rel), true)
	sf.Path = rel
	return f, sf, err
}
